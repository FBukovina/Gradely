private data class StrokePath(
    val data: String,
    val width: Float,
    val cap: StrokeCap,
    val join: StrokeJoin,
)

private fun plain(data: String, width: Float = 1.5f) =
    StrokePath(data, width, StrokeCap.Butt, StrokeJoin.Miter)

private fun capped(data: String, width: Float = 1.5f) =
    StrokePath(data, width, StrokeCap.Round, StrokeJoin.Miter)

private fun joined(data: String, width: Float = 1.5f) =
    StrokePath(data, width, StrokeCap.Butt, StrokeJoin.Round)

private fun rounded(data: String, width: Float = 1.5f) =
    StrokePath(data, width, StrokeCap.Round, StrokeJoin.Round)

private fun circle() =
    plain("M22 12C22 6.47715 17.5228 2 12 2C6.47715 2 2 6.47715 2 12C2 17.5228 6.47715 22 12 22C17.5228 22 22 17.5228 22 12Z")

private fun hugeicon(
    name: String,
    vararg paths: StrokePath,
    autoMirror: Boolean = false,
): ImageVector =
    ImageVector.Builder(
        name = "Hugeicons Stroke Rounded: $name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
        autoMirror = autoMirror,
    ).apply {
        paths.forEach { path ->
            addPath(
                pathData = PathParser().parsePathString(path.data).toNodes(),
                fill = null,
                stroke = SolidColor(Color.Black),
                strokeLineWidth = path.width,
                strokeLineCap = path.cap,
                strokeLineJoin = path.join,
            )
        }
    }.build()
