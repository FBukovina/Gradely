export type TranslationKey = keyof typeof catalogs.en;

export function translate(
  locale: WebLocale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const template: string = catalogs[locale]?.[key] ?? catalogs.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, token: string) =>
    params[token] != null ? String(params[token]) : `{${token}}`,
  );
}

export function detectDefaultLocale(): WebLocale {
  if (typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("cs")) {
    return "cs";
  }
  return "en";
}
